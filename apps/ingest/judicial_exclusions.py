"""裁判書入庫前的案件類型排除（任務 35，規格 §4.6）。

依法不公開的案件類型：性侵害案件、少年事件、部分家事事件。

**採保守排除，非精細判斷。** 規格用詞是「部分家事」——多數家事案件
（繼承、分割遺產、簡單的扶養費）本來就公開，只有涉及未成年子女、
保護令等的才受限制。要精確分辨「這一部分」需要逐案認定訴訟性質，
本模組沒有能力也不該嘗試做這種逐案認定（司法院自己的月封存檔資料
沒有提供「是否限制公開」的旗標欄位，只有字別代碼與案由文字）。

因此策略是關鍵字比對案由（JTITLE）：含保護令、家暴、性侵害等字樣者
排除，其餘家事案件維持入庫——寧可漏掉少數應排除但關鍵字沒比對到的
案件，也不要因為「家事」兩個字就整類排除掉大量本該公開的繼承分割
案件。這與 ``apps.compliance.risk``「不知道就當作未確定」是同一個
保守方向的體現，只是這裡「保守」意味著精準關鍵字，不是大範圍排除。

**這是 blocking gate，接在 ``ingest_judicial_opendata`` 的寫入之前。**
未通過者完全不建立 ``Document``，不是建立後標記不公開——依法不公開的
案件不該連內部資料庫都留一份可查詢的記錄。
"""
from __future__ import annotations

import re

__all__ = ["is_excluded_case", "EXCLUDED_PATTERN"]

#: 案由或字別含這些字樣者排除。
#:
#: - 少年事件：少年事件處理法規定不公開
#: - 性侵害／性騷擾：性侵害犯罪防治法規定不公開被害人身分，
#:   保守起見整篇排除而非嘗試遮蔽。**案由實務上寫的是刑法罪名
#:   「妨害性自主」，不是「性侵害」三個字**——只列「性侵害」會
#:   漏掉幾乎所有真實案由，這個落差是實測真實案由文字才發現的。
#: - 家暴／保護令：家庭暴力防治法的保護令事件不公開
EXCLUDED_PATTERN = re.compile(
    "少年|少調|少友|保護令|暫時保護令|妨害性自主|性侵害|性騷擾|"
    "兒童及少年性剝削|家庭暴力|家暴"
)


def is_excluded_case(*, case_title: str = "", case_category: str = "") -> bool:
    """該筆案件是否應排除入庫。

    Args:
        case_title: 案由（JTITLE），如「損害賠償(交通)」「聲請核發保護令」。
        case_category: 字別（JCASE），部分字別代碼本身即標示案件類型
            （如「少調」「家護」），與案由一併比對以提高涵蓋率。
    """
    text = f"{case_title} {case_category}"
    return bool(EXCLUDED_PATTERN.search(text))
